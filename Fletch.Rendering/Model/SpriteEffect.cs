namespace Fletch.Rendering.Model
{
    /// <summary>
    /// The sprite effects that can be applied when rendering a sprite.
    /// </summary>
    public enum SpriteEffect
    {
        /// <summary>
        /// No sprite effect applied.
        /// </summary>
        None = 0,

        /// <summary>
        /// Flips the sprite horizontally.
        /// </summary>
        FlipHorizontally = 1,

        /// <summary>
        /// Flips the sprite vertically.
        /// </summary>
        FlipVertically = 2,
    }
}

